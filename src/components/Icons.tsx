// Icon wrapper component for easy usage throughout the app
interface IconProps {
  name: string;
  size?: number;
  className?: string;
}

export function Icon({ name, size = 24, className = "" }: IconProps) {
  const IconMap: Record<string, React.ComponentType<any>> = {
    Scale: ScaleIcon,
    Flag: FlagIcon,
    ShieldCheck: ShieldCheckIcon,
    ArrowRight: ArrowRightIcon,
    ExternalLink: ExternalLinkIcon,
    MessageCircle: MessageCircleIcon,
    Coffee: CoffeeIcon,
    Users: UsersIcon,
    Megaphone: MegaphoneIcon,
    Sun: SunIcon,
    Moon: MoonIcon,
    Menu: MenuIcon,
    X: XIcon,
  };
  const Component = IconMap[name];
  if (!Component) return null;
  const finalClass = `${className} w-${size} h-${size}`.trim();
  return <Component className={finalClass} />;
}
